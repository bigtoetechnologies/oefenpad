// Extend the shared namespace rather than replacing it — common.js also
// hangs helpers off window.OEFENPAD, and load order between the two varies.
window.OEFENPAD = window.OEFENPAD || {};
Object.assign(window.OEFENPAD, {
    normLang: function (lang) { return lang === 'en-us' ? 'en' : lang; },
    entries: function (cat, lang) {
        var l = this.normLang(lang);
        return (cat.words || []).filter(function (e) { return e[l]; });
    },
    words: function (cat, lang, opts) {
        var l = this.normLang(lang);
        var list = (cat.words || []).map(function (e) { return e[l]; }).filter(Boolean);
        if (opts && opts.singleOnly) {
            list = list.filter(function (w) { return /^[\p{L}]+$/u.test(w); });
        }
        return list;
    }
});
